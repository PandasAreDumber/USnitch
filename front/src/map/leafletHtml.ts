import { Platform } from 'react-native';
import parkingLots from './parkingLots.json';

// Builds the self-contained Leaflet page rendered by CampusMap (WebView on
// native, iframe on web). When the first tiles finish loading it posts
// "map-ready" back to React so the loading screen can be dismissed.

// University of Utah main campus
const CENTER: [number, number] = [40.7649, -111.8421];
// Keep the user on campus, with room for every parking lot: [south-west, north-east]
const BOUNDS: [[number, number], [number, number]] = [
  [40.748, -111.86],
  [40.777, -111.812],
];

// Lot outlines from the university GIS snapshot, generated by
// scripts/build_front_parking.mjs. "<" is escaped so the data can't close the
// inline <script> tag.
const PARKING_LOTS_JSON = JSON.stringify(parkingLots).replace(/</g, '\\u003c');

const STADIA_API_KEY = process.env.EXPO_PUBLIC_STADIA_API_KEY ?? '';

// Stadia only serves tiles without an API key to localhost, so phones need a
// key. Until one is set, native falls back to CARTO's keyless dark tiles.
const USE_STADIA = Boolean(STADIA_API_KEY) || Platform.OS === 'web';

const STADIA_LAYER = `L.tileLayer('https://tiles.stadiamaps.com/tiles/alidade_smooth_dark/{z}/{x}/{y}{r}.{ext}${
  STADIA_API_KEY ? `?api_key=${encodeURIComponent(STADIA_API_KEY)}` : ''
}', {
      minZoom: 0,
      maxZoom: 20,
      attribution: '&copy; <a href="https://www.stadiamaps.com/" target="_blank">Stadia Maps</a> &copy; <a href="https://openmaptiles.org/" target="_blank">OpenMapTiles</a> &copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors',
      ext: 'png'
    })`;

const CARTO_LAYER = `L.tileLayer('https://{s}.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}{r}.png', {
      subdomains: 'abcd',
      maxZoom: 20,
      attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors &copy; <a href="https://carto.com/attributions">CARTO</a>'
    })`;

export const MAP_READY_MESSAGE = 'map-ready';

export function buildLeafletHtml(bottomInset = 0) {
  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
  <link rel="stylesheet" href="https://unpkg.com/leaflet@1.9.4/dist/leaflet.css" />
  <script src="https://unpkg.com/leaflet@1.9.4/dist/leaflet.js"></script>
  <style>
    html, body, #map { height: 100%; margin: 0; padding: 0; background: #43333A; }
    .leaflet-control-attribution { background: rgba(67, 51, 58, 0.8) !important; color: #D7A49E; }
    .leaflet-control-attribution a { color: #FB503F; }
    .leaflet-container .leaflet-control-attribution { font-size: 9px; line-height: 1.4; padding: 0 4px; }
    .leaflet-bottom { bottom: ${Number(bottomInset) || 0}px; }
    .leaflet-popup-content-wrapper, .leaflet-popup-tip { background: #43333A; color: #F3E3E0; }
    .leaflet-popup-content { margin: 10px 14px; font: 13px/1.4 system-ui, sans-serif; }
    .lot-name { font-weight: 700; color: #FFFFFF; }
    .lot-meta { color: #D7A49E; }
    .lot-risk { margin-top: 4px; display: flex; align-items: center; gap: 6px; color: #F3E3E0; font-weight: 600; }
    .lot-swatch { width: 10px; height: 10px; border-radius: 2px; display: inline-block; }
    .sighting-dot { background: #FFD46B; border: 3px solid #fff; border-radius: 50%; box-shadow: 0 0 0 5px rgba(255,212,107,.2), 0 2px 12px #0009; }
    .selection-dot { background: #FB503F; border: 3px solid #fff; border-radius: 50%; box-shadow: 0 0 0 6px #FB503F44; }
    /* Fixed pin for picking a location: the map moves underneath it, and its tip
       marks the map's center. Hidden unless the map is in picking mode. */
    #center-pin { display: none; position: absolute; left: 50%; top: 50%; z-index: 1000; pointer-events: none; }
    body.picking #center-pin { display: block; }
    #center-pin svg { position: absolute; left: -18px; top: -44px; width: 36px; height: 44px; transition: transform .15s ease-out; filter: drop-shadow(0 3px 4px #0008); }
    #center-pin.moving svg { transform: translateY(-8px); }
    #center-pin .pin-shadow { position: absolute; left: -5px; top: -3px; width: 10px; height: 6px; border-radius: 50%; background: #0007; }
  </style>
</head>
<body>
  <div id="map"></div>
  <div id="center-pin" aria-hidden="true">
    <div class="pin-shadow"></div>
    <svg viewBox="0 0 36 44"><path d="M18 43C18 43 33 27.5 33 17A15 15 0 0 0 3 17C3 27.5 18 43 18 43Z" fill="#E4332D" stroke="#fff" stroke-width="2.5"/><circle cx="18" cy="17" r="5.5" fill="#fff"/></svg>
  </div>
  <script>
    function postMessage(message) {
      if (window.ReactNativeWebView) {
        window.ReactNativeWebView.postMessage(typeof message === 'string' ? message : JSON.stringify(message));
      } else if (window.parent !== window) {
        window.parent.postMessage(message, '*');
      }
    }
    var notified = false;
    function notifyReady() {
      if (!notified) { notified = true; postMessage('${MAP_READY_MESSAGE}'); }
    }

    var bounds = L.latLngBounds(${JSON.stringify(BOUNDS)});
    var map = L.map('map', {
      center: ${JSON.stringify(CENTER)},
      zoom: 15,
      minZoom: 14,
      maxBounds: bounds,
      maxBoundsViscosity: 1.0,
      zoomControl: false,
    });
    // Drop the "Leaflet" link; the tile and map data credits must stay.
    map.attributionControl.setPrefix(false);

    var tiles = ${USE_STADIA ? STADIA_LAYER : CARTO_LAYER};

    // Report ready once the first tiles render (or fail), whichever comes first.
    tiles.once('load', notifyReady);
    tiles.once('tileerror', notifyReady);
    tiles.addTo(map);

    // Before predictions arrive (or for a lot the server didn't score) outlines are neutral.
    var NO_DATA_COLOR = '#8A7A80';
    var MIN_SCORE = 0.05; // the model's floor ("nothing reported")
    // Full red = the highest score in the current predictions, so the riskiest
    // lot for the picked time is always red and the rest are scaled against it.
    // Recomputed every time new predictions arrive (see updateMaxScore).
    var MAX_SCORE = 1;
    function updateMaxScore(scores) {
      var max = MIN_SCORE;
      if (scores) Object.keys(scores).forEach(function (id) {
        var s = scores[id];
        if (typeof s === 'number' && isFinite(s) && s > max) max = s;
      });
      MAX_SCORE = max;
    }

    // Heat scale for the lot outlines: yellow = very unlikely, red = most likely.
    var HEAT_STOPS = [
      [0.0, [255, 230, 80]],  // yellow
      [0.5, [255, 140, 30]],  // orange
      [1.0, [230, 30, 30]],   // red
    ];
    function heatLevel(score) {
      // Every lot at the floor (nothing predicted anywhere): all yellow.
      if (MAX_SCORE - MIN_SCORE < 1e-6) return 0;
      return Math.max(0, Math.min(1, (score - MIN_SCORE) / (MAX_SCORE - MIN_SCORE)));
    }
    function heatColor(score) {
      var t = heatLevel(score);
      for (var i = 1; i < HEAT_STOPS.length; i++) {
        var a = HEAT_STOPS[i - 1], b = HEAT_STOPS[i];
        if (t <= b[0]) {
          var f = (t - a[0]) / (b[0] - a[0]);
          var rgb = a[1].map(function (v, k) { return Math.round(v + (b[1][k] - v) * f); });
          return 'rgb(' + rgb.join(',') + ')';
        }
      }
      return 'rgb(' + HEAT_STOPS[HEAT_STOPS.length - 1][1].join(',') + ')';
    }
    function likelihoodLabel(score) {
      var t = heatLevel(score);
      if (t >= 0.66) return 'Most likely';
      if (t >= 0.33) return 'Likely';
      if (t >= 0.1) return 'Possible';
      return 'Unlikely';
    }

    function escapeText(value) {
      return String(value).replace(/[&<>"']/g, function (c) {
        return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
      });
    }

    var likelihoods = null;
    function lotStyle(feature) {
      var score = likelihoods ? likelihoods[feature.properties.id] : undefined;
      var known = typeof score === 'number' && isFinite(score);
      var color = known ? heatColor(score) : NO_DATA_COLOR;
      return {
        color: color,
        fillColor: color,
        weight: known ? 2.5 : 1.25,
        opacity: known ? 1 : 0.7,
        fillOpacity: known ? 0.12 : 0.06,
      };
    }
    function lotPopup(feature) {
      var p = feature.properties;
      var score = likelihoods ? likelihoods[p.id] : undefined;
      var html =
        '<div class="lot-name">' + escapeText(p.name) + '</div>' +
        '<div class="lot-meta">Lot ' + escapeText(p.lot) + ' · ' +
        (p.type === 'garage' ? 'Garage' : 'Surface lot') + '</div>';
      if (typeof score === 'number' && isFinite(score)) {
        html += '<div class="lot-risk"><span class="lot-swatch" style="background:' + heatColor(score) + '"></span>' +
          likelihoodLabel(score) + ' · score ' + score.toFixed(2) + '</div>';
      }
      return html;
    }

    var selecting = false;
    var lots = L.geoJSON(${PARKING_LOTS_JSON}, {
      style: lotStyle,
      onEachFeature: function (feature, layer) {
        layer.bindPopup(function () { return lotPopup(feature); });
      },
    }).addTo(map);

    var sightingsLayer = L.layerGroup().addTo(map);
    var markers = {};
    var selection;
    var centerPin = document.getElementById('center-pin');

    // In picking mode the picked location is always the map's center.
    function postCenter() {
      var center = map.getCenter();
      postMessage({type:'location-selected',latitude:center.lat,longitude:center.lng});
    }

    window.USnitchMap = {
      update: function (state) {
        if (!state || state.type !== 'usnitch-state') return;
        var nextSelecting = Boolean(state.pickingLocation);
        if (nextSelecting !== selecting) {
          selecting = nextSelecting;
          document.body.classList.toggle('picking', selecting);
          lots.eachLayer(function (layer) {
            if (selecting) layer.unbindPopup();
            else layer.bindPopup(function () { return lotPopup(layer.feature); });
          });
          map.closePopup();
          // Start with the pin's current spot picked, so it matches what's shown.
          if (selecting && !state.selectedLocation) postCenter();
        }
        var nextLikelihoods = state.likelihoods || null;
        if (JSON.stringify(nextLikelihoods) !== JSON.stringify(likelihoods)) {
          likelihoods = nextLikelihoods;
          updateMaxScore(likelihoods);
          lots.setStyle(lotStyle);
          // Biggest risks on top so their outlines aren't hidden by neighbours.
          var order = [];
          lots.eachLayer(function (layer) { order.push(layer); });
          order.sort(function (a, b) {
            var sa = likelihoods ? likelihoods[a.feature.properties.id] || 0 : 0;
            var sb = likelihoods ? likelihoods[b.feature.properties.id] || 0 : 0;
            return sa - sb;
          }).forEach(function (layer) { layer.bringToFront(); });
        }
        var ids = {};
        (state.sightings || []).slice().sort(function (a, b) {
          return Date.parse(a.observed_at) - Date.parse(b.observed_at);
        }).forEach(function (s, index) {
          if (!Number.isFinite(s.latitude) || !Number.isFinite(s.longitude)) return;
          ids[s.id] = true;
          if (!markers[s.id]) {
            var icon = L.divIcon({className:'sighting-dot',iconSize:[18,18],iconAnchor:[9,9]});
            markers[s.id] = L.marker([s.latitude,s.longitude], {icon:icon, keyboard:true, title:'Open sighting photo', alt:'Open sighting photo'})
              .bindTooltip('Sighting · ' + new Date(s.observed_at).toLocaleTimeString([], {hour:'numeric',minute:'2-digit'}))
              .on('click', function () { if (!selecting) postMessage({type:'sighting-selected',id:s.id}); })
              .addTo(sightingsLayer);
          }
          markers[s.id].setZIndexOffset(index * 20);
        });
        Object.keys(markers).forEach(function (id) {
          if (!ids[id]) { sightingsLayer.removeLayer(markers[id]); delete markers[id]; }
        });
        if (state.selectedLocation && selecting) {
          // The center pin shows the location; move the map only when the location
          // came from somewhere else (e.g. "Use my location"), not from a drag.
          if (selection) { map.removeLayer(selection); selection = null; }
          var target = L.latLng(state.selectedLocation.latitude, state.selectedLocation.longitude);
          if (map.getCenter().distanceTo(target) > 1) map.setView(target, Math.max(map.getZoom(), 17), {animate:false});
        } else if (state.selectedLocation) {
          var point = [state.selectedLocation.latitude,state.selectedLocation.longitude];
          if (!selection || !selection.getLatLng().equals(point)) map.setView(point, Math.max(map.getZoom(), 17), {animate:false});
          if (!selection) {
            selection = L.marker(point,{icon:L.divIcon({className:'selection-dot',iconSize:[20,20],iconAnchor:[10,10]})}).addTo(map);
          } else selection.setLatLng(point);
        } else if (selection) { map.removeLayer(selection); selection = null; }
      }
    };
    window.addEventListener('message', function (event) {
      if (event.source === window.parent) window.USnitchMap.update(event.data);
    });
    map.on('movestart', function () {
      if (selecting) centerPin.classList.add('moving');
    });
    map.on('moveend', function () {
      centerPin.classList.remove('moving');
      if (selecting) postCenter();
    });
    // The bridge is ready independently of the tile network.
    setTimeout(notifyReady, 600);
  </script>
</body>
</html>`;
}
